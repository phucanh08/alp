export function alpWordmarkHeight(width: number): number {
  return Math.round((width * ALP_WORDMARK_HEIGHT) / ALP_WORDMARK_WIDTH);
}

interface AlpMarkProps {
  size?: number;
  color?: string;
}

export function AlpMark({ size = 16, color = "currentColor" }: AlpMarkProps) {
  return (
    <Svg width={size} height={size} viewBox="0 0 1254 1254">
      <Path d={ALP_MARK_PATH} fill={color} fillRule="evenodd" />
    </Svg>
  );
}

interface AlpWordmarkProps {
  width?: number;
  color?: string;
}

function AlpWordmarkSvg({ width = 128, color = "currentColor" }: AlpWordmarkProps) {
  return (
    <Svg width={width} height={alpWordmarkHeight(width)} viewBox={ALP_WORDMARK_VIEWBOX}>
      <Path d={ALP_WORDMARK_PATH} fill={color} fillRule="evenodd" />
    </Svg>
  );
}

// Follows the theme foreground unless the caller passes a color.
export const AlpWordmark = withUnistyles(AlpWordmarkSvg, (theme) => ({
  color: theme.colors.foreground,
}));
