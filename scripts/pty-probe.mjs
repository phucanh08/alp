// TEMPORARY CI probe (t-1e02 P2): node-pty ConPTY input under Node vs Bun. Removed before merge.
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const fs = require('node:fs');
const mode = process.argv[2] ?? 'plain';
const pty = require('node-pty');
let conin, opened = [];
const open = fs.openSync;
if (mode === 'fd') fs.openSync = (t, f, m) => { const fd = open(t, f, m); opened.push([String(t), f, fd]); if (f === 'w') conin = fd; return fd; };
const child = pty.spawn(process.env.ComSpec || 'cmd.exe', [], { cols: 80, rows: 24, useConpty: true });
fs.openSync = open;
let out = '';
child.onData(d => { out += d; });
console.log(`[probe ${mode} ${process.versions.bun ? 'bun' : 'node'}] opened`, JSON.stringify(opened), 'same fs as require(fs):', require('fs') === fs);
await new Promise(r => setTimeout(r, 2000));
const text = 'set /a 19*19+1000\r';
if (mode === 'fd' && conin !== undefined) fs.writeSync(conin, text); else child.write(text);
await new Promise(r => setTimeout(r, 3000));
console.log(`[probe ${mode} ${process.versions.bun ? 'bun' : 'node'}] got 1361:`, out.includes('1361'), JSON.stringify(out.slice(-300)));
child.kill();
process.exit(0);
