#!/usr/bin/env node
// Builds ALP as one self-contained executable with `bun build --compile` (t-1e02): the CLI, alpd,
// alp-web and the ACP agent in one image, plus the templates, the web app and the native terminal
// helper as embedded files that @anhlp/alp-core/packaged extracts to <ALP_HOME>/cache/<version>/
// against the sha256 manifest written here. The npm build is unchanged; this only reads its output.
//
//   node scripts/build-binary.mjs [--target bun-darwin-arm64] [--outfile dist/bin/alp] [--no-build]
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { ROOT } from './workspace-build-lib.mjs';
import { EXECUTABLE_MARKER } from '../packages/core/src/packaged.js';

const TARGETS = {
  'bun-darwin-arm64': 'darwin-arm64', 'bun-darwin-x64': 'darwin-x64',
  'bun-linux-x64': 'linux-x64-glibc', 'bun-linux-arm64': 'linux-arm64-glibc',
  'bun-windows-x64': 'win32-x64',
};
// Bun's own architecture: Node may run translated (an x64 Node under Rosetta on an arm64 Mac).
const hostTarget = () => {
  const arch = spawnSync('bun', ['-e', 'console.log(process.arch)'], { encoding: 'utf8', shell: process.platform === 'win32' }).stdout?.trim() || process.arch;
  return `bun-${process.platform === 'win32' ? 'windows' : process.platform}-${arch}`;
};

/** Files under `directory`, relative and with forward slashes, sorted. */
async function files(directory, prefix = '') {
  const out = [];
  for (const entry of (await readdir(directory, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...await files(path.join(directory, entry.name), relative));
    else if (entry.isFile()) out.push(relative);
  }
  return out;
}

/** The embedded assets: name in the cache → source file. @param {string} slot */
export async function binaryAssets(slot) {
  const assets = new Map();
  const add = async (directory, prefix, keep = () => true) => {
    for (const file of await files(directory)) if (keep(file)) assets.set(`${prefix}/${file}`, path.join(directory, file));
  };
  await add(path.join(ROOT, 'templates'), 'templates');
  await add(path.join(ROOT, 'packages/cli/dist/alp-web'), 'alp-web');
  // Only this target's helper: native-terminal.ts checks it against terminal-owner.c and its manifest.
  await add(path.join(ROOT, 'packages/cli/dist/terminal-native'), 'terminal-native', file => file === 'terminal-owner.c' || file.startsWith(`prebuilt/${slot}/`));
  return assets;
}

/** The generated entry: register the executable, refuse script paths, then run the CLI. */
export function entrySource({ version, assets }) {
  const imports = [], manifest = [];
  [...assets].forEach(([name, { file, sha256, size }], index) => {
    imports.push(`import asset${index} from ${JSON.stringify(file)} with { type: 'file' };`);
    manifest.push(`  ${JSON.stringify(name)}: { path: asset${index}, sha256: ${JSON.stringify(sha256)}, size: ${size} },`);
  });
  return `// Generated by scripts/build-binary.mjs; do not edit.
import { registerPackaged, isScript } from '@anhlp/alp-core/packaged';

// Discovery (findDaemonEntry) recognises ALP's executable by this string; keep it a literal.
export const ALP_EXECUTABLE_IDENTITY = ${JSON.stringify(EXECUTABLE_MARKER)};
${imports.join('\n')}

registerPackaged({
  version: ${JSON.stringify(version)},
  assets: {
${manifest.join('\n')}
  },
  roles: {
    daemon: () => import('../dist/alpd.js'),
    web: () => import('../dist/alp-web.js'),
    acp: () => import('../dist/acp.js'),
  },
});

// Packaged-mode guard: a caller that still spawns process.execPath with a script path would re-enter
// this entry (Bun passes the script as an ordinary argument); refuse loudly instead of running the CLI.
const first = process.argv[2];
if (first !== undefined && isScript(first)) {
  console.error(\`alp: this is the ALP executable; it cannot run the script \${first}. Use its subcommands (alp daemon run, alp web serve, alp bridge).\`);
  process.exit(2);
}
await import('../dist/cli.js');
`;
}

async function main() {
  const { values } = parseArgs({ options: { target: { type: 'string' }, outfile: { type: 'string' }, 'no-build': { type: 'boolean' } } });
  const target = values.target ?? hostTarget();
  const slot = TARGETS[target];
  if (!slot) throw new Error(`Unsupported target ${target}; expected one of ${Object.keys(TARGETS).join(', ')}`);
  const run = (command, args) => {
    const result = spawnSync(command, args, { cwd: ROOT, stdio: 'inherit', shell: process.platform === 'win32' });
    if (result.status !== 0) throw new Error(`${command} ${args.join(' ')} failed (${result.status ?? result.error})`);
  };
  if (!values['no-build']) run('npm', ['run', 'build']);
  const { version } = JSON.parse(await readFile(path.join(ROOT, 'packages/cli/package.json'), 'utf8'));
  const assets = new Map();
  for (const [name, file] of await binaryAssets(slot)) {
    const bytes = await readFile(file);
    assets.set(name, { file, sha256: createHash('sha256').update(bytes).digest('hex'), size: bytes.length });
  }
  const directory = path.join(ROOT, 'packages/cli/.binary');
  await mkdir(directory, { recursive: true });
  const entry = path.join(directory, 'entry.mjs');
  await writeFile(entry, entrySource({ version, assets }));
  await writeFile(path.join(directory, 'assets.json'), JSON.stringify({ version, target, slot, assets: Object.fromEntries([...assets].map(([name, { sha256, size }]) => [name, { sha256, size }])) }, null, 2));
  const outfile = path.resolve(ROOT, values.outfile ?? path.join('dist/bin', target.includes('windows') ? 'alp.exe' : 'alp'));
  await mkdir(path.dirname(outfile), { recursive: true });
  run('bun', ['build', '--compile', `--target=${target}`, entry, '--outfile', outfile]);
  console.log(`Built ${outfile} (${target}, ${assets.size} embedded assets, version ${version})`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) await main();
